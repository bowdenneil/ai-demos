function cyberSimSelectScenario(key) {
  cyberSimState.scenario = key;
  document.querySelectorAll('.cyber-sim-scenario-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.scenario === key);
  });
  cyberSimReset();
}

function cyberSimRenderSteps() {
  const scenario = CYBER_SIM_SCENARIOS[cyberSimState.scenario];
  if (!scenario) return;

  const attackHTML = scenario.attackSteps.map((s, i) => `
    <div class="cyber-sim-step ${i <= cyberSimState.attackStep ? 'active' : ''} ${i === cyberSimState.attackStep ? 'current' : ''}" id="cyber-attack-step-${i}">
      <span class="cyber-sim-step-icon">${s.icon}</span>
      <div class="cyber-sim-step-info">
        <span class="cyber-sim-step-label">${s.label}</span>
        ${i === cyberSimState.attackStep ? `<span class="cyber-sim-step-detail">${s.detail}</span>` : ''}
      </div>
    </div>
  `).join('');

  const defenseHTML = scenario.defenseSteps.map((s, i) => `
    <div class="cyber-sim-step ${i <= cyberSimState.defenseStep ? 'active' : ''} ${i === cyberSimState.defenseStep ? 'current' : ''}" id="cyber-defense-step-${i}">
      <span class="cyber-sim-step-icon">${s.icon}</span>
      <div class="cyber-sim-step-info">
        <span class="cyber-sim-step-label">${s.label}</span>
        ${i === cyberSimState.defenseStep ? `<span class="cyber-sim-step-detail">${s.detail}</span>` : ''}
      </div>
    </div>
  `).join('');

  document.getElementById('cyber-attack-steps').innerHTML = attackHTML;
  document.getElementById('cyber-defense-steps').innerHTML = defenseHTML;
}

async function cyberSimStart() {
  if (cyberSimState.running) return;

  cyberSimState.running = true;
  const startBtn = document.getElementById('cyber-sim-start');
  startBtn.disabled = true;
  startBtn.textContent = '⏳ Running...';
  document.getElementById('cyber-sim-status').textContent = '🔴 Attack in progress...';
  document.getElementById('cyber-sim-status').className = 'cyber-sim-status running';

  const scenario = CYBER_SIM_SCENARIOS[cyberSimState.scenario];
  const speed = cyberSimState.speed;

  // Attack phase
  document.getElementById('cyber-attack-badge').textContent = 'Active';
  document.getElementById('cyber-attack-badge').className = 'cyber-sim-badge active';
  document.getElementById('cyber-defense-badge').textContent = 'Monitoring';
  document.getElementById('cyber-defense-badge').className = 'cyber-sim-badge monitoring';

  // Clear logs
  document.getElementById('cyber-attack-log').innerHTML = '';
  document.getElementById('cyber-defense-log').innerHTML = '';
  cyberSimState.attackLog = [];
  cyberSimState.defenseLog = [];
  cyberSimState.timeline = [];

  // Run attack steps
  for (let i = 0; i < scenario.attackSteps.length; i++) {
    if (!cyberSimState.running) break;
    cyberSimState.attackStep = i;
    const step = scenario.attackSteps[i];
    const timestamp = new Date(Date.now() - (scenario.attackSteps.length - i) * 60000).toLocaleTimeString('en-US', { hour12: false });

    cyberSimAddLog('attack', timestamp, step.icon, step.label, step.detail);
    cyberSimAddTimeline(timestamp, 'attack', step);
    cyberSimRenderSteps();

    // Defense kicks in after step 2
    if (i === 2) {
      await cyberSimSleep(800 / speed);
      document.getElementById('cyber-sim-status').textContent = '🟢 Defense responding...';
      // Start defense in parallel
      cyberSimRunDefense(scenario, speed);
    }

    await cyberSimSleep(step.duration / speed);
  }

  // Wait for defense to finish
  while (cyberSimState.running && cyberSimState.defenseStep < scenario.defenseSteps.length - 1) {
    await cyberSimSleep(200);
  }

  if (!cyberSimState.running) return;

  cyberSimState.running = false;
  startBtn.disabled = false;
  startBtn.textContent = '▶ Start Simulation';
  document.getElementById('cyber-sim-status').textContent = '✅ Simulation complete';
  document.getElementById('cyber-sim-status').className = 'cyber-sim-status done';
  document.getElementById('cyber-attack-badge').textContent = 'Contained';
  document.getElementById('cyber-attack-badge').className = 'cyber-sim-badge contained';
  document.getElementById('cyber-defense-badge').textContent = 'Complete';
  document.getElementById('cyber-defense-badge').className = 'cyber-sim-badge done';

  // Show summary
  document.getElementById('cyber-sim-summary').style.display = 'block';
}

async function cyberSimRunDefense(scenario, speed) {
  for (let i = 0; i < scenario.defenseSteps.length; i++) {
    if (!cyberSimState.running) break;
    cyberSimState.defenseStep = i;
    const step = scenario.defenseSteps[i];
    const timestamp = new Date().toLocaleTimeString('en-US', { hour12: false });

    cyberSimAddLog('defense', timestamp, step.icon, step.label, step.detail);
    cyberSimAddTimeline(timestamp, 'defense', step);
    cyberSimRenderSteps();

    await cyberSimSleep(step.duration / speed);
  }
}

function cyberSimAddLog(side, timestamp, icon, label, detail) {
  const logEl = document.getElementById(`cyber-${side}-log`);
  if (!logEl) return;

  // Clear empty state
  const empty = logEl.querySelector('.cyber-sim-log-empty');
  if (empty) empty.remove();

  const entry = document.createElement('div');
  entry.className = 'cyber-sim-log-entry';
  entry.innerHTML = `
    <span class="cyber-sim-log-time">${timestamp}</span>
    <span class="cyber-sim-log-icon">${icon}</span>
    <div class="cyber-sim-log-content">
      <span class="cyber-sim-log-label">${label}</span>
      <span class="cyber-sim-log-detail">${detail}</span>
    </div>
  `;
  logEl.appendChild(entry);
  logEl.scrollTop = logEl.scrollHeight;

  if (side === 'attack') {
    cyberSimState.attackLog.push({ timestamp, icon, label, detail });
  } else {
    cyberSimState.defenseLog.push({ timestamp, icon, label, detail });
  }
}

function cyberSimAddTimeline(timestamp, side, step) {
  cyberSimState.timeline.push({ timestamp, side, ...step });
}

function cyberSimReset() {
  cyberSimState.running = false;
  cyberSimState.attackStep = -1;
  cyberSimState.defenseStep = -1;
  cyberSimState.attackLog = [];
  cyberSimState.defenseLog = [];
  cyberSimState.timeline = [];

  const startBtn = document.getElementById('cyber-sim-start');
  if (startBtn) {
    startBtn.disabled = false;
    startBtn.textContent = '▶ Start Simulation';
  }

  const status = document.getElementById('cyber-sim-status');
  if (status) {
    status.textContent = '⚪ Ready';
    status.className = 'cyber-sim-status';
  }

  const attackBadge = document.getElementById('cyber-attack-badge');
  if (attackBadge) { attackBadge.textContent = 'Idle'; attackBadge.className = 'cyber-sim-badge'; }

  const defenseBadge = document.getElementById('cyber-defense-badge');
  if (defenseBadge) { defenseBadge.textContent = 'Idle'; defenseBadge.className = 'cyber-sim-badge'; }

  const attackLog = document.getElementById('cyber-attack-log');
  if (attackLog) attackLog.innerHTML = '<div class="cyber-sim-log-empty">Waiting for simulation to start...</div>';

  const defenseLog = document.getElementById('cyber-defense-log');
  if (defenseLog) defenseLog.innerHTML = '<div class="cyber-sim-log-empty">Waiting for detection...</div>';

  const summary = document.getElementById('cyber-sim-summary');
  if (summary) summary.style.display = 'none';

  cyberSimRenderSteps();
}

function cyberSimSleep(ms) {
  return new Promise(resolve => setTimeout(resolve, ms));
}

async function cyberSimGenerateBrief() {
  const btn = document.getElementById('cyber-sim-brief-btn');
  const output = document.getElementById('cyber-sim-brief-output');
  if (!btn || !output) return;

  const scenario = CYBER_SIM_SCENARIOS[cyberSimState.scenario];
  btn.disabled = true;
  btn.textContent = '⏳ Generating...';
  output.innerHTML = '<span class="typing-cursor"></span> <span style="color:var(--text-dim)">AI analyst generating incident briefing...</span>';

  const attackLog = cyberSimState.attackLog.map(l => `[${l.timestamp}] ${l.label}: ${l.detail}`).join('\n');
  const defenseLog = cyberSimState.defenseLog.map(l => `[${l.timestamp}] ${l.label}: ${l.detail}`).join('\n');

  const systemPrompt = `You are an elite AI security incident responder. Generate a professional incident briefing based on the simulation data. Use markdown formatting with headers, bullet points, and tables where appropriate. Structure: Executive Summary → Attack Timeline → Defense Response → Key Findings → Recommendations.`;

  const userMessage = `## Scenario: ${scenario.name}

## Attack Log
${attackLog}

## Defense Log
${defenseLog}

## Timeline Events
${cyberSimState.timeline.length} total events recorded.

Generate a comprehensive incident briefing. Include MITRE ATT&CK mapping, detection effectiveness, response time analysis, and recommendations for improving defenses.`;

  try {
    const fullText = await callLLM([
      { role: 'system', content: systemPrompt },
      { role: 'user', content: userMessage }
    ], (chunk) => {
      output.innerHTML = formatMarkdown(chunk) + '<span class="typing-cursor"></span>';
    });

    output.innerHTML = formatMarkdown(fullText);
  } catch (e) {
    output.innerHTML = `<div class="error-card"><strong>❌ Failed.</strong><br><span class="dim">${e.message || 'Unknown error'}</span></div>`;
  }

  btn.disabled = false;
  btn.textContent = 'Generate AI Briefing';
}
